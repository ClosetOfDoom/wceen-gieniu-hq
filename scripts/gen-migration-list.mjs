#!/usr/bin/env node
// Writes netlify/shared/migrationList.js from what is actually in
// supabase/migrations/.
//
// The MIGRACJE panel has to compare "files in the repo" against "rows in
// applied_migrations". The browser cannot read a directory and the Netlify
// bundler does not ship .sql files, so the list is generated at build time
// instead of being typed out — a hand-kept list would drift the first time
// somebody added a migration and forgot, and a panel that silently stops
// mentioning a file is worse than no panel.
//
//   node scripts/gen-migration-list.mjs          # write
//   node scripts/gen-migration-list.mjs --check  # fail if stale (used by verify)

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs'
import { join } from 'path'

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
const rootDir = process.platform === 'win32' ? root.replace(/^\//, '') : root
const SRC = join(rootDir, 'supabase/migrations')
const OUT = join(rootDir, 'netlify/shared/migrationList.js')

const files = readdirSync(SRC).filter(f => f.endsWith('.sql')).sort()

const body = `// GENERATED by scripts/gen-migration-list.mjs — do not edit by hand.
// Run \`npm run gen:migrations\` after adding or removing a file in
// supabase/migrations/. \`npm run verify\` fails when this is stale.
//
// Every .sql file in supabase/migrations/, sorted. The MIGRACJE panel in
// Diagnostics compares this against public.applied_migrations and names the
// ones with no row.
export const MIGRATION_FILES = [
${files.map(f => `  '${f}',`).join('\n')}
]

/** The register itself. Without it every other file reads as unapplied. */
export const MIGRATION_REGISTER_FILE = '20261020_applied_migrations.sql'
`

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') === body) {
    console.log(`  pass migrationList.js matches supabase/migrations/ (${files.length} files)`)
    process.exit(0)
  }
  console.error('  FAIL netlify/shared/migrationList.js is stale')
  console.error('       supabase/migrations/ holds: ' + files.join(', '))
  console.error('       run: npm run gen:migrations')
  process.exit(1)
}

writeFileSync(OUT, body, 'utf8')
console.log(`migrationList.js: ${files.length} plików`)
