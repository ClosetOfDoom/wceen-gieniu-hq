// import-reply-templates.mjs — regenerates netlify/shared/replyTemplates.js from Filip's PAKIETY.html
// (the customer-reply templates: Pakiet Pamięciowy, 3 Zadziwiające Techniki, Językozak AI, Kurs, WSZTP).
//
//   node scripts/import-reply-templates.mjs [path-to-PAKIETY.html]
//
// The builders in the page are run in a sandbox with a stubbed `document`; the activation-code input returns
// the literal marker {{CODE}}, which the server replaces with the code Filip types before approving.
// The customer-facing text stays as written (Polish): customers write in Polish.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(process.argv[2] ?? 'C:/Users/filip/OneDrive/Desktop/Praca/HTMLS/PAKIETY.html')
const out = resolve(here, '../netlify/shared/replyTemplates.js')

const page = readFileSync(src, 'utf8')
const script = [...page.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]).join('\n')
const start = script.indexOf('const L = {')
const end = script.indexOf('const BUILD=')
if (start < 0 || end < 0) throw new Error('PAKIETY.html: the link table or the BUILD table was not found')

const sandbox = { document: { getElementById: () => ({ value: '{{CODE}}' }) } }
vm.createContext(sandbox)
vm.runInContext(`${script.slice(start, end)}\nglobalThis.__out = { pp: buildPP(), tech: buildTech(), jzk: buildJzk(), kurs: buildKurs(), wsztp: buildWsztp() }`, sandbox)

const META = {
  pp: { label: 'Pakiet Pamięciowy (119 zł)', needsCode: false },
  tech: { label: '3 Zadziwiające Techniki (49 zł)', needsCode: false },
  jzk: { label: 'Językozak AI (347 zł) + kod aktywacyjny', needsCode: true },
  kurs: { label: 'Kurs „Jak się uczyć” (549 zł)', needsCode: false },
  wsztp: { label: 'WSZTP 2026 — powitanie i bonusy', needsCode: false },
}

const templates = {}
for (const [id, t] of Object.entries(sandbox.__out)) {
  if (!t.subject || !t.html || !t.plain) throw new Error(`template ${id} is incomplete`)
  if (/\$\{|undefined/.test(t.html + t.plain)) throw new Error(`template ${id} has unresolved placeholders`)
  templates[id] = { id, ...META[id], subject: t.subject, html: t.html, plain: t.plain }
}

const body = `// replyTemplates.js — GENERATED by scripts/import-reply-templates.mjs from HTMLS/PAKIETY.html. Do not edit by hand.
// Customer-reply templates (Polish: the customers write in Polish). {{CODE}} = the Językozak AI activation code.

export const CODE_MARKER = '{{CODE}}'

export const REPLY_TEMPLATES = ${JSON.stringify(templates, null, 2)}

export const REPLY_TEMPLATE_IDS = Object.keys(REPLY_TEMPLATES)

/** The template with the activation code filled in. Throws for a template that needs a code when none was given. */
export function renderReply(id, { code } = {}) {
  const t = REPLY_TEMPLATES[id]
  if (!t) throw new Error(\`unknown reply template: \${id}\`)
  const c = String(code ?? '').trim()
  if (t.needsCode && !/^[A-Za-z0-9][A-Za-z0-9_-]{5,63}$/.test(c)) throw new Error('this template needs a valid activation code')
  const fill = (s) => s.split(CODE_MARKER).join(c)
  return { id, subject: t.subject, html: fill(t.html), plain: fill(t.plain), needsCode: t.needsCode }
}
`
writeFileSync(out, body)
console.log(`replyTemplates.js written: ${Object.keys(templates).join(', ')}`)
